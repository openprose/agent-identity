#!/bin/bash
# Install the agent-shell integration for the current user. Idempotent.
# Run after `agent-identity login --broker URL`, which records your org and App.
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd -P)
config="${XDG_CONFIG_HOME:-$HOME/.config}/agent-identity"
bin="$HOME/.local/share/agent-identity/bin"
mkdir -p "$config" "$bin" "$HOME/.local/bin"
chmod 700 "$config"

ln -sf "$here/../cli/agent-identity.ts" "$HOME/.local/bin/agent-identity"
ln -sf "$here/gh" "$bin/gh"
ln -sf "$here/agent-env.sh" "$config/agent-env.sh"

command -v agent-identity >/dev/null || { echo "put ~/.local/bin on PATH first" >&2; exit 1; }
org=$(agent-identity config | jq -r .org)
[[ "$org" =~ ^[A-Za-z0-9-]+$ ]] || { echo "log in first: agent-identity login --broker URL" >&2; exit 1; }
bot=$(agent-identity bot)
bot_name=$(jq -r .name <<< "$bot")
bot_email=$(jq -r .email <<< "$bot")

# In repositories with a remote in your org: commit as the bot, route SSH
# remotes through HTTPS, and authenticate with broker-minted tokens only.
cat > "$config/agent.gitconfig" <<GITCONFIG
# Generated by agent-identity install.sh. Loaded only in agent shells
# (GIT_CONFIG_COUNT from agent-env.sh).
[includeIf "hasconfig:remote.*.url:https://github.com/$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:git@github.com:$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:ssh://git@github.com/$org/**"]
	path = bot.gitconfig
[url "https://github.com/$org/"]
	insteadOf = git@github.com:$org/
	insteadOf = ssh://git@github.com/$org/
[credential "https://github.com/$org"]
	useHttpPath = true
	helper =
	helper = !agent-identity git-credential
GITCONFIG
printf '[user]\n\tname = %s\n\temail = %s\n' "$bot_name" "$bot_email" > "$config/bot.gitconfig"

# Per-user settings, kept if already present.
if [ ! -f "$config/env.sh" ]; then
  cat > "$config/env.sh" <<ENVSH
# agent-identity settings, sourced by agent-env.sh in every shell.
export AGENT_IDENTITY_ORG=$org
# Variables whose presence marks an agent shell (space-separated). Add your
# orchestrator's session variable here if it sets one.
AGENT_IDENTITY_DETECT="AGENT_IDENTITY_AGENT CLAUDECODE AI_AGENT"
# What agent shells may do with your personal login for commands not routed
# to the bot: allow (default), read, or deny.
# export AGENT_IDENTITY_PERSONAL=read
# Variables naming the agent session, recorded with each token.
# export AGENT_IDENTITY_LABEL_VARS="CLAUDE_CODE_SESSION_ID CODEX_THREAD_ID"
ENVSH
fi

line="[ -f \"$config/agent-env.sh\" ] && . \"$config/agent-env.sh\""
for rc in "$HOME/.zshenv" "$HOME/.zshrc" "$HOME/.bashrc"; do
  [ -e "$rc" ] || [ "$rc" = "$HOME/.zshenv" ] || continue
  grep -qF 'agent-identity/agent-env.sh' "$rc" 2>/dev/null \
    || printf '\n# agent-identity: agent shells act as the GitHub App bot on %s repositories\n%s\n' "$org" "$line" >> "$rc"
done
echo "installed for $org as $bot_name. New agent shells pick it up; check one with: command -v gh"
