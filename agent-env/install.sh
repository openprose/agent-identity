#!/bin/bash
# Install the agent-shell integration for the current user. Idempotent.
# Run after `agent-identity login --broker URL`, which records your org and App.
#
#   agent-env/install.sh               install, or refresh after an upgrade
#   agent-env/install.sh --uninstall   remove it (run `agent-identity logout` first)
set -euo pipefail
here=$(cd "$(dirname "$0")" && pwd -P)
config="${XDG_CONFIG_HOME:-$HOME/.config}/agent-identity"
bin="$HOME/.local/share/agent-identity/bin"
rcs=("$HOME/.zshenv" "$HOME/.zshrc" "$HOME/.bashrc")

if [ "${1:-}" = --uninstall ]; then
  for rc in "${rcs[@]}"; do
    [ -f "$rc" ] || continue
    grep -qF 'agent-identity' "$rc" || continue
    tmp=$(mktemp)
    grep -vF -e 'agent-identity/agent-env.sh' -e '# agent-identity: agent shells act as' "$rc" > "$tmp" || true
    cat "$tmp" > "$rc"
    rm -f "$tmp"
  done
  rm -f "$HOME/.local/bin/agent-identity" "$bin/gh" "$config/agent-env.sh" "$config/agent.gitconfig" "$config/bot.gitconfig"
  echo "uninstalled. Kept $config/env.sh and any session; run 'agent-identity logout' before uninstalling to revoke it."
  exit 0
fi

mkdir -p "$config" "$bin" "$HOME/.local/bin"
chmod 700 "$config"

ln -sf "$here/../cli/agent-identity.ts" "$HOME/.local/bin/agent-identity"
ln -sf "$here/gh" "$bin/gh"
ln -sf "$here/agent-env.sh" "$config/agent-env.sh"

command -v agent-identity >/dev/null || { echo "put ~/.local/bin on PATH first" >&2; exit 1; }
org=$(agent-identity config | jq -r .org)
[[ "$org" =~ ^[A-Za-z0-9-]+$ ]] || { echo "log in first: agent-identity login --broker URL" >&2; exit 1; }
bot=$(agent-identity bot)
bot_name=$(jq -r .name <<< "$bot")
bot_email=$(jq -r .email <<< "$bot")

# The credential helpers git uses for github.com today (outside agent shells),
# honouring "helper =" resets. They stay behind the broker for other owners.
url_helpers=$(GIT_CONFIG_COUNT=0 git config --get-all credential.https://github.com.helper 2>/dev/null || true)
generic_helpers=$(GIT_CONFIG_COUNT=0 git config --get-all credential.helper 2>/dev/null || true)
if printf '%s\n' "$url_helpers" | grep -qx ''; then
  previous=$(printf '%s\n' "$url_helpers" | awk 'NF == 0 { list = ""; next } { list = list $0 "\n" } END { printf "%s", list }')
else
  previous=$(printf '%s\n%s\n' "$generic_helpers" "$url_helpers" | grep -v '^$' || true)
fi
previous_lines=""
while IFS= read -r helper; do
  [ -n "$helper" ] || continue
  case "$helper" in *agent-identity*) continue ;; esac
  previous_lines+=$'\t'"helper = $helper"$'\n'
done <<< "$previous"

# In agent shells: in repositories with a remote in your org, commit as the
# bot; route SSH and www. spellings through https://github.com; ask the broker
# first for every github.com credential (it answers only for your org, in any
# letter case, and git falls through to your usual helpers for anyone else);
# and for your org's exact URL prefix, use the broker only.
cat > "$config/agent.gitconfig" <<GITCONFIG
# Generated by agent-identity install.sh. Loaded only in agent shells
# (GIT_CONFIG_* from agent-env.sh). Re-run install.sh after changing your
# global git credential helpers.
[includeIf "hasconfig:remote.*.url:https://github.com/$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:git@github.com:$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:ssh://git@github.com/$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:ssh://git@github.com:22/$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:github.com:$org/**"]
	path = bot.gitconfig
[includeIf "hasconfig:remote.*.url:https://www.github.com/$org/**"]
	path = bot.gitconfig
[url "https://github.com/"]
	insteadOf = https://www.github.com/
[url "https://github.com/$org/"]
	insteadOf = git@github.com:$org/
	insteadOf = ssh://git@github.com/$org/
	insteadOf = ssh://git@github.com:22/$org/
	insteadOf = github.com:$org/
[credential "https://github.com"]
	useHttpPath = true
	helper =
	helper = !agent-identity git-credential
${previous_lines}[credential "https://github.com/$org"]
	useHttpPath = true
	helper =
	helper = !agent-identity git-credential
GITCONFIG
printf '[user]\n\tname = %s\n\temail = %s\n' "$bot_name" "$bot_email" > "$config/bot.gitconfig"

# Per-user settings, kept if already present.
if [ ! -f "$config/env.sh" ]; then
  cat > "$config/env.sh" <<ENVSH
# agent-identity settings, sourced by agent-env.sh in every shell.
export AGENT_IDENTITY_ORG=$org
# Variables whose presence marks an agent shell (space-separated). Add your
# orchestrator's session variable here if it sets one.
AGENT_IDENTITY_DETECT="AGENT_IDENTITY_AGENT CLAUDECODE AI_AGENT CODEX_THREAD_ID"
# What agent shells may do with your personal login for commands not routed
# to the bot: read (default), allow, or deny.
# export AGENT_IDENTITY_PERSONAL=read
# Variables naming the agent session, recorded with each token.
# export AGENT_IDENTITY_LABEL_VARS="CLAUDE_CODE_SESSION_ID CODEX_THREAD_ID"
ENVSH
fi

line="[ -f \"$config/agent-env.sh\" ] && . \"$config/agent-env.sh\""
for rc in "${rcs[@]}"; do
  [ -e "$rc" ] || [ "$rc" = "$HOME/.zshenv" ] || continue
  grep -qF 'agent-identity/agent-env.sh' "$rc" 2>/dev/null && continue
  # Start on a fresh line, without adding blank lines --uninstall would leave.
  if [ -s "$rc" ] && [ -n "$(tail -c 1 "$rc")" ]; then printf '\n' >> "$rc"; fi
  printf '# agent-identity: agent shells act as the GitHub App bot on %s repositories\n%s\n' "$org" "$line" >> "$rc"
done
echo "installed for $org as $bot_name. New agent shells pick it up; check with: agent-identity doctor"
